#!/usr/bin/env python3
"""Merge a Dictée recording session into a standard NeMo/ASR manifest JSONL.

Dictée (https://github.com/benjaminbellamy/Dictee) records prompts into:
    audio_00.wav, audio_01.wav, ...
and writes a tab-separated transcript manifest:
    trans.txt (audio_NN.wav<TAB><prompt>)

This script matches the recorded WAV files with their companion metadata
(generated by g2p_error_simulation or wikipron_dual_pronunciations), computes
audio duration in seconds via the standard Python wave module, and outputs a
manifest JSONL with standard fields:
    {"audio_filepath": "...", "text": "<phoneme>", "duration": 1.23, ...}
"""

import argparse
import csv
import json
import re
import sys
import wave
from pathlib import Path


def get_wav_duration(wav_path):
    """Return the duration of a WAV file in seconds rounded to 2 decimal places."""
    with wave.open(str(wav_path), "rb") as wf:
        frames = wf.getnframes()
        rate = wf.getframerate()
        if rate == 0:
            return 0.0
        return round(frames / float(rate), 2)


def load_metadata_rows(metadata_path):
    """Load metadata rows from CSV or JSONL file into a list of dicts."""
    p = Path(metadata_path)
    if not p.exists():
        raise FileNotFoundError(f"Metadata file not found: {p}")

    rows = []
    if p.suffix == ".jsonl":
        with p.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    rows.append(json.loads(line))
    else:
        with p.open("r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for r in reader:
                # Typecast numeric and boolean strings where applicable
                typed = {}
                for k, v in r.items():
                    if v == "" or v is None:
                        typed[k] = None
                    elif v.lower() == "true":
                        typed[k] = True
                    elif v.lower() == "false":
                        typed[k] = False
                    elif re.fullmatch(r"-?\d+", v):
                        typed[k] = int(v)
                    elif re.fullmatch(r"-?\d+\.\d+", v):
                        typed[k] = float(v)
                    else:
                        typed[k] = v
                rows.append(typed)
    return rows


def resolve_dictee_dir(dictee_dir):
    """Locate the directory containing audio_*.wav or trans.txt.

    Dictée creates a subfolder named after the input text file (e.g. sentences/).
    This handles passing the parent folder, the file itself, or the subfolder.
    """
    p = Path(dictee_dir)
    if p.is_file():
        p = p.parent / p.stem

    # If audio files or trans.txt are in a 'sentences' child directory
    if (p / "sentences").is_dir():
        child = p / "sentences"
        if list(child.glob("audio_*.wav")) or (child / "trans.txt").exists():
            return child

    # If sentences.txt exists in p and no wavs in p, Dictée will output to p / "sentences"
    if (p / "sentences.txt").exists() and not list(p.glob("audio_*.wav")):
        return p / "sentences"

    return p


def merge_dictee_session(
    dictee_dir,
    metadata_path,
    output_manifest_path,
    project_root=None,
    dry_run=False,
):
    """Merge Dictée WAV recordings and companion metadata into manifest JSONL.

    Parameters:
        dictee_dir: Directory containing Dictée audio_*.wav and/or trans.txt.
        metadata_path: Path to companion CSV or JSONL metadata file.
        output_manifest_path: Path to output manifest JSONL file.
        project_root: Optional root directory to make audio_filepath relative to.
        dry_run: If True, simulates missing WAV files without raising error.
    """
    audio_dir = resolve_dictee_dir(dictee_dir)
    metadata_rows = load_metadata_rows(metadata_path)

    if project_root is not None:
        root_path = Path(project_root).resolve()
    else:
        root_path = Path.cwd().resolve()

    # Find existing WAV files
    wav_files = sorted(audio_dir.glob("audio_*.wav")) if audio_dir.exists() else []
    wav_map = {}
    for wf in wav_files:
        m = re.search(r"audio_(\d+)\.wav$", wf.name)
        if m:
            idx = int(m.group(1))
            wav_map[idx] = wf

    # Check trans.txt if present
    trans_map = {}
    trans_file = audio_dir / "trans.txt" if audio_dir.exists() else None
    if trans_file and trans_file.exists():
        with trans_file.open("r", encoding="utf-8") as f:
            for line in f:
                parts = line.strip().split("\t", 1)
                if len(parts) == 2:
                    wav_name, text_val = parts
                    m = re.search(r"audio_(\d+)\.wav$", wav_name)
                    if m:
                        trans_map[int(m.group(1))] = text_val

    n_samples = len(metadata_rows)
    n_wavs = len(wav_map)

    # Determine mapping mode:
    # 1. 1-to-1 mode: audio_NN.wav corresponds to sample_id == NN
    # 2. Pair mode: audio_NN.wav corresponds to pair_id == NN (when 50 recordings for 100 samples)
    is_pair_mode = False
    if n_wavs > 0 and n_wavs < n_samples and "pair_id" in metadata_rows[0]:
        unique_pairs = {
            r.get("pair_id") for r in metadata_rows if r.get("pair_id") is not None
        }
        if n_wavs == len(unique_pairs):
            is_pair_mode = True

    manifest_entries = []
    missing_audio = []

    for i, row in enumerate(metadata_rows):
        sample_id = row.get("sample_id", i)
        target_idx = row.get("pair_id", sample_id) if is_pair_mode else sample_id

        wav_path = wav_map.get(target_idx)
        if wav_path and wav_path.exists():
            duration = get_wav_duration(wav_path)
            try:
                rel_path = str(wav_path.resolve().relative_to(root_path))
            except ValueError:
                rel_path = str(wav_path)
        else:
            duration = 0.0
            placeholder_name = f"audio_{target_idx:02d}.wav"
            rel_path = str((audio_dir / placeholder_name).relative_to(root_path))
            missing_audio.append(placeholder_name)

        # Standard manifest entry
        # "text" is strictly the phonemic (IPA) transcription
        phoneme_text = row.get("phoneme", "")
        entry = {
            "audio_filepath": rel_path,
            "text": phoneme_text,
            "duration": duration,
        }

        # Include additional metadata fields
        for k, v in row.items():
            if k not in entry:
                entry[k] = v

        manifest_entries.append(entry)

    if missing_audio and not dry_run:
        raise FileNotFoundError(
            f"Missing {len(missing_audio)} audio files in {audio_dir} "
            f"(e.g. {missing_audio[:3]}). Use dry_run=True to build placeholder manifest."
        )

    out_p = Path(output_manifest_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    with out_p.open("w", encoding="utf-8") as f:
        for entry in manifest_entries:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    return manifest_entries


def main():
    parser = argparse.ArgumentParser(
        description="Merge Dictée recordings with metadata into manifest JSONL."
    )
    parser.add_argument(
        "--dictee-dir",
        required=True,
        help="Directory containing Dictée audio_*.wav or trans.txt.",
    )
    parser.add_argument(
        "--metadata",
        required=True,
        help="Path to metadata file (CSV or JSONL).",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Path for destination manifest JSONL.",
    )
    parser.add_argument(
        "--project-root",
        default=None,
        help="Root directory for relative audio filepaths (default: current working dir).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Generate manifest with placeholders if audio files are not yet recorded.",
    )

    args = parser.parse_args()

    try:
        entries = merge_dictee_session(
            dictee_dir=args.dictee_dir,
            metadata_path=args.metadata,
            output_manifest_path=args.output,
            project_root=args.project_root,
            dry_run=args.dry_run,
        )
        print(
            f"Successfully generated manifest with {len(entries)} entries at: {args.output}"
        )
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
